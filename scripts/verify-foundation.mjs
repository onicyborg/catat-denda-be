import 'dotenv/config';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { NestFactory } from '@nestjs/core';
import request from 'supertest';
import * as argon2 from 'argon2';

import { configure } from '../dist/http.js';
import { PrismaService } from '../dist/prisma/prisma.service.js';
// A fresh schema isolates auth, rate limits and constraints from local operational data.
const schema = 'qa_' + randomBytes(6).toString('hex');
const url = new URL(process.env.DATABASE_URL); url.searchParams.set('schema', schema);
process.env.DATABASE_URL = url.toString();
process.env.SESSION_SECRET = randomBytes(32).toString('hex');
process.env.APP_BASE_URL = 'http://localhost:3000';
execFileSync('pnpm', ['prisma:deploy'], { stdio: 'inherit', env: process.env });
const { AppModule } = await import('../dist/app.module.js');
const app = await NestFactory.create(AppModule, { logger: false }); configure(app); await app.init();
const db=app.get(PrismaService), http=app.getHttpServer();
const email='qa@example.test', password=randomBytes(20).toString('hex');
const login=() => request(http).post('/api/v1/auth/login').set('Origin',process.env.APP_BASE_URL).send({email,password});
const cookie=r=>r.headers['set-cookie'][0].split(';')[0];
try {
 execFileSync('pnpm',['admin:bootstrap'],{env:{...process.env,ADMIN_BOOTSTRAP_EMAIL:'bootstrap@example.test',ADMIN_BOOTSTRAP_PASSWORD:password},stdio:'pipe'});
 assert.throws(()=>execFileSync('pnpm',['admin:bootstrap'],{env:{...process.env,ADMIN_BOOTSTRAP_EMAIL:'bootstrap@example.test',ADMIN_BOOTSTRAP_PASSWORD:password+'changed'},stdio:'pipe'}));
 const bootstrap=await db.user.findUniqueOrThrow({where:{email:'bootstrap@example.test'}});
 assert(await argon2.verify(bootstrap.passwordHash,password));
 const user=await db.user.create({ data:{email,passwordHash:await argon2.hash(password)} });
 await request(http).get('/api/v1/health/live').expect(200);
 await request(http).get('/api/v1/auth/me').expect(401);
 await request(http).post('/api/v1/auth/login').send({email,password}).expect(403);
 await request(http).post('/api/v1/auth/login').set('Origin',process.env.APP_BASE_URL).send({email,password,extra:1}).expect(422);
 const first=await login().expect(201), second=await login().expect(201);
 const token=first.body.data.csrfToken;
 if (process.env.NODE_ENV === 'production') assert.match(first.headers['set-cookie'][0], /Secure/);
 assert.match(first.headers['set-cookie'][0],/HttpOnly/);assert.match(first.headers['set-cookie'][0],/SameSite=Lax/);assert.match(first.headers['set-cookie'][0],/Path=\/api\/v1/);
 await request(http).get('/api/v1/auth/me').set('Cookie',cookie(first)).expect(200);
 await db.user.update({where:{id:user.id},data:{isActive:false}});
 await request(http).get('/api/v1/auth/me').set('Cookie',cookie(first)).expect(401);
 await db.user.update({where:{id:user.id},data:{isActive:true}});
 await request(http).get('/api/v1/health/ready').set('Cookie',cookie(first)).expect(200);
 await request(http).post('/api/v1/auth/logout').set('Origin',process.env.APP_BASE_URL).set('Cookie',cookie(first)).expect(403);
 await request(http).post('/api/v1/auth/change-password').set('Origin',process.env.APP_BASE_URL).set('Cookie',cookie(first)).set('X-CSRF-Token',token).send({currentPassword:password,newPassword:'new-password-secure-123'}).expect(201);
 await request(http).get('/api/v1/auth/me').set('Cookie',cookie(second)).expect(401);
 await request(http).post('/api/v1/auth/logout').set('Origin',process.env.APP_BASE_URL).set('Cookie',cookie(first)).set('X-CSRF-Token',token).expect(201);
 await request(http).get('/api/v1/auth/me').set('Cookie',cookie(first)).expect(401);
 const current=await request(http).post('/api/v1/auth/login').set('Origin',process.env.APP_BASE_URL).send({email,password:'new-password-secure-123'}).expect(201);
 await db.authSession.updateMany({where:{userId:user.id},data:{expiresAt:new Date(0)}});
 await request(http).get('/api/v1/auth/me').set('Cookie',cookie(current)).expect(401);
 await login().expect(429);
 await assert.rejects(db.violationType.create({data:{code:'BAD',name:'Invalid',category:'OTHER',defaultAmountPerPerson:0}}));
 const employee=await db.employee.create({data:{displayName:'QA',normalizedName:'qa'}});
 await db.employeeAlias.create({data:{employeeId:employee.id,aliasDisplay:'Alias',aliasNormalized:'alias'}});
 await assert.rejects(db.employeeAlias.create({data:{employeeId:employee.id,aliasDisplay:'Alias',aliasNormalized:'alias'}}));
 const fine=await db.fineCase.create({data:{createdBy:user.id}});
 await assert.rejects(db.fineCaseMember.create({data:{fineCaseId:fine.id,assignedAmount:-1}}));
 await db.fineCaseMember.create({data:{fineCaseId:fine.id,employeeId:employee.id}});
 await assert.rejects(db.employee.delete({where:{id:employee.id}}));
 const member=await db.fineCaseMember.findFirstOrThrow({where:{fineCaseId:fine.id}});
 const key='12345678-1234-4234-8234-123456789012';
 const entry=await db.paymentEntry.create({data:{fineCaseMemberId:member.id,kind:'PAYMENT',amount:1,method:'CASH',effectiveAt:new Date(),idempotencyKey:key,requestHash:'0'.repeat(64),recordedBy:user.id}});
 await assert.rejects(db.paymentEntry.create({data:{fineCaseMemberId:member.id,kind:'PAYMENT',amount:1,method:'CASH',effectiveAt:new Date(),idempotencyKey:key,requestHash:'0'.repeat(64),recordedBy:user.id}}));
 const reversal={fineCaseMemberId:member.id,kind:'REVERSAL',amount:1,effectiveAt:new Date(),originalPaymentId:entry.id,requestHash:'0'.repeat(64),recordedBy:user.id};
 await db.paymentEntry.create({data:{...reversal,idempotencyKey:'22345678-1234-4234-8234-123456789012'}});
 await assert.rejects(db.paymentEntry.create({data:{...reversal,idempotencyKey:'32345678-1234-4234-8234-123456789012'}}));
 const audits=await db.auditLog.findMany();assert(audits.some(a=>a.action==='PASSWORD_CHANGE'));assert(!JSON.stringify(audits).includes(password));
 console.log('PASS: fresh migration, auth, cookie, validation, CSRF, revoke, expiry, rate-limit, audit and database constraints.');
} finally {
 await db.$executeRawUnsafe(`DROP SCHEMA "${schema}" CASCADE`);
 await app.close();
}
